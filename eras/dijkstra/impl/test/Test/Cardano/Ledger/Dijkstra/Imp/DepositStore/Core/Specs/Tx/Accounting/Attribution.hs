-- | Fundable operation plans and independent observations of signed attribution.
-- Required changes come from priced outputs and recorded input deposits. Observed
-- attribution uses the production projections shared by settlement and legacy balance.
module Test.Cardano.Ledger.Dijkstra.Imp.DepositStore.Core.Specs.Tx.Accounting.Attribution (
  everyDeclarationForm,
  activeAndInactiveZeroChildren,
  AttributionAmounts (..),
  attributionAmounts,
  observedTopTxChange,
  observedLocalSubTxChanges,
  observedOriginatingSubTxChanges,
  subTxNetChanges,
) where

import Cardano.Ledger.Coin (Coin (..))
import Cardano.Ledger.Dijkstra.Core
import qualified Cardano.Ledger.Dijkstra.Rules as Accounting
import Cardano.Ledger.Val ((<->))
import qualified Data.OMap.Strict as OMap
import Lens.Micro
import Test.Cardano.Ledger.Common (Gen, chooseInt)
import Test.Cardano.Ledger.Dijkstra.Imp.DepositStore.Core.Specs.Tx.Accounting (
  AccountingScenario,
