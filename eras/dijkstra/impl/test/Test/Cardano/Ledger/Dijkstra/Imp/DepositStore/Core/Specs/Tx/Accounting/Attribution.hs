 )
import qualified Test.Cardano.Ledger.Dijkstra.Imp.DepositStore.Core.Specs.Tx.Accounting.TopTx as Parent
import qualified Test.Cardano.Ledger.Dijkstra.Imp.DepositStore.Core.Specs.Tx.SubTx as SubTx
import Test.Cardano.Ledger.Dijkstra.Imp.DepositStore.Core.Specs.Tx.TopTx.Release (ReleaseTx (..))

-- | Every child form occurs in every sample, including both signs of local and
-- delegated changes. Independent magnitudes prevent cancelling pairs from masking
-- attribution errors. The parent's own operations can allocate, release or net to zero.
everyDeclarationForm :: Gen AccountingScenario
everyDeclarationForm = do
  ownAllocations <- chooseInt (0, 3)
  ownReleases <- chooseInt (0, 3)
  localAllocation <- chooseInt (1, 3)
  delegatedAllocation <- chooseInt (1, 3)
  localRelease <- chooseInt (1, 3)
  delegatedRelease <- chooseInt (1, 3)
  zeroOperations <- chooseInt (1, 3)
  scenario
    (bodyOperations ownAllocations ownReleases)
    [ bodyOperations localAllocation 0
    , bodyOperations delegatedAllocation 0
    , bodyOperations 0 localRelease
    , bodyOperations 0 delegatedRelease
    , bodyOperations zeroOperations zeroOperations
    , bodyOperations 0 0
    ]

-- | Two explicit-zero children in every sample: one reallocates positive deposits,
-- the other has no Store operations. Their parent independently allocates, releases
-- or has a zero change, proving the children do not replace its own contribution.
activeAndInactiveZeroChildren :: Gen AccountingScenario
activeAndInactiveZeroChildren = do
  operations <- chooseInt (1, 3)
  ownAllocations <- chooseInt (0, 3)
  ownReleases <- chooseInt (0, 3)
  scenario
    (bodyOperations ownAllocations ownReleases)
    [bodyOperations operations operations, bodyOperations 0 0]

-- | Independently observed magnitudes for the four nonzero children generated by
-- 'everyDeclarationForm'. These come from actual Store records/output prices,
-- never declaration interpretation. Releases are represented as positive magnitudes.
data AttributionAmounts = AttributionAmounts
  { ownTopTxChange :: Coin
  , localAllocationAmount :: Integer
  , delegatedAllocationAmount :: Integer
  , localReleaseAmount :: Integer
  , delegatedReleaseAmount :: Integer
  }
  deriving (Show)

-- | Resolve the ordered fixture's actual changes into names usable by the DSL.
-- Unexpected body counts or signs indicate a generator/funding contract failure.
attributionAmounts :: ReleaseTx -> AttributionAmounts
attributionAmounts proposal =
  case subTxNetChanges proposal of
    [ Coin localAllocation
      , Coin delegatedAllocation
      , Coin localRelease
      , Coin delegatedRelease
      , Coin 0
      , Coin 0
      ]
        | localAllocation > 0 && delegatedAllocation > 0 && localRelease < 0 && delegatedRelease < 0 ->
            AttributionAmounts
              (Parent.ownNetDeposit proposal)
              localAllocation
              delegatedAllocation
              (negate localRelease)
              (negate delegatedRelease)
    changes -> error $ "Unexpected settlement attribution fixture changes: " <> show changes

-- | Independent required changes for the ordered children: new output prices
-- minus deposits recorded against the consumed ordinary inputs.
subTxNetChanges :: ReleaseTx -> [Coin]
subTxNetChanges proposal = zipWith (<->) (SubTx.allocatedDeposits proposal) (SubTx.releasedDeposits proposal)

-- | Observe the production TopTx projection consumed by settlement and legacy
-- balance. Its expectation must be computed independently by the specification.
observedTopTxChange :: ReleaseTx -> Coin
observedTopTxChange = Accounting.attributedTopTxNetUTxODeposit . (^. bodyTxL) . unsignedTx

-- | Observe each child's local signed share, retaining body order and zero entries.
observedLocalSubTxChanges :: ReleaseTx -> [Coin]
observedLocalSubTxChanges =
  map
    (Accounting.locallyAccountedSubTxNetUTxODeposit . (^. bodyTxL . subTxNetUTxODepositChangeTxBodyL))
    . OMap.elems
    . (^. bodyTxL . subTransactionsTxBodyL)
    . unsignedTx

-- | Observe each child's originating signed amount independently of where that
-- amount is accounted. Delegation must not erase its originating contribution.
observedOriginatingSubTxChanges :: ReleaseTx -> [Coin]
observedOriginatingSubTxChanges =
  map (Accounting.declaredSubTxNetUTxODeposit . (^. bodyTxL . subTxNetUTxODepositChangeTxBodyL))
    . OMap.elems
    . (^. bodyTxL . subTransactionsTxBodyL)
    . unsignedTx
